#!/usr/bin/env node
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { attachScaffoldDecisionFixture } from '../../../../scripts/fixtures/user-decision/build-fixture.mjs';
import { mvcFixture } from './fixtures.mjs';
import { technicalDigest, validateTechnicalDesign } from '../scripts/validate-technical-design.mjs';
import { hash, read } from '../../../../scripts/lib/strategic-handoff-io.mjs';
import { enforceTechnicalDesign } from '../../../../scripts/lib/technical-design-boundary.mjs';
import { compileDefaultImplementationContract, evaluateContractFreshness, loadCompilerContract } from '../../../../scripts/lib/implementation-contract-compiler.mjs';
import { loadSkillRegistry } from '../../../../scripts/lib/skill-registry.mjs';
const root = mkdtempSync(path.join(tmpdir(), 'yss-technical-design-'));
let checks = 0;
try {
  const mvc = mvcFixture(root);
  const validate = data => validateTechnicalDesign(data, { root });
  assert.equal((await validate(mvc)).architecture_family, 'layered-mvc'); checks++;
  async function rejected(change, pattern) {
    const data = structuredClone(mvc); change(data); data.digest = technicalDigest(data);
    await assert.rejects(() => validate(data), pattern); checks++;
  }
  await rejected(d => { d.architecture.family = 'mixed'; }, /not one of/);
  await rejected(d => { d.architecture.project_id = 'wrong'; }, /登记架构不匹配/);
  await rejected(d => { d.architecture.decision_digest = `sha256:${'0'.repeat(64)}`; }, /来源摘要漂移/);
  await rejected(d => { d.traceability.pop(); }, /缺少规则或场景承接/);
  await rejected(d => { d.traceability[1].scenario_tests.pop(); }, /成功\/失败测试/);
  await rejected(d => { d.traceability[0].tactical_refs = ['aggregate.fake']; }, /设计落点悬空/);
  await rejected(d => { d.design.module_catalog[0].depends_on = ['module.repository']; }, /模块依赖越界/);
  await rejected(d => { d.design.consistency_policy.transaction_boundary = ''; }, /non-empty/);
  await rejected(d => { d.design.aggregate_catalog = []; }, /Additional properties/);
  await rejected(d => { d.design.test_seams[0].subject_ref = 'missing'; }, /设计对象悬空/);
  await rejected(d => { d.status = 'stale'; }, /状态不可消费/);
  await rejected(d => { d.traceability[0].disposition = 'conflict'; }, /未闭合承接/);
  const deferred = structuredClone(mvc); deferred.status = 'approved';
  Object.assign(deferred.traceability[0], { disposition: 'deferred', reason: '下一版', risk: '提交不可用', owner: '维护者', followup_ticket_ref: 'ticket.next', verification_plan: '回归提交', target_version: 'v2' });
  deferred.digest = technicalDigest(deferred);
  await assert.rejects(() => validateTechnicalDesign(deferred, { root, sliceRef: 'slice.submit' }), /未闭合承接/); checks++;
  assert.equal((await validateTechnicalDesign(deferred, { root, sliceRef: 'slice.other' })).architecture_family, 'layered-mvc'); checks++;
  deferred.traceability[0].dependency_status = 'unknown'; deferred.digest = technicalDigest(deferred);
  await assert.rejects(() => validateTechnicalDesign(deferred, { root, sliceRef: 'slice.other' }), /未闭合承接/); checks++;
  writeFileSync(path.join(root, 'spec.md'), 'changed');
  await assert.rejects(() => validate(mvc), /输入摘要漂移/); checks++;
  mvcFixture(root);
  const old = read(fileURLToPath(new URL('../../yss-tactical-design/tests/fixtures/valid-tactical-design.yaml', import.meta.url)));
  await assert.rejects(() => validate(old), /显式 --legacy-ddd/); checks++;
  assert.equal((await validateTechnicalDesign(old, { root, legacyDdd: true })).result, 'legacy-ddd-read-only'); checks++;
  const ddd = structuredClone(mvc); ddd.architecture.family = 'domain-driven';
  writeFileSync(path.join(root, 'registration.json'), JSON.stringify({ project_id: 'example', status: 'current', architecture_identity: { architecture_family: 'domain-driven' } }));
  ddd.architecture.decision_digest = hash(readFileSync(path.join(root, 'registration.json'))); ddd.design = old;
  ddd.inputs.push({ kind: 'strategic', ref: 'spec.md', version: 'v1', digest: hash(readFileSync(path.join(root, 'spec.md'))) });
  for (const row of ddd.traceability) Object.assign(row, { tactical_refs: [old.test_seams[0].subject_ref], test_seam_refs: [old.test_seams[0].seam_id], scenario_tests: ['success','failure'].map(outcome => ({ outcome, seam_ref: old.test_seams[0].seam_id })) });
  ddd.digest = technicalDigest(ddd);
  assert.equal((await validate(ddd)).architecture_family, 'domain-driven'); checks++;
  ddd.design.aggregate_catalog[0].api_exposure = 'public'; ddd.digest = technicalDigest(ddd);
  await assert.rejects(() => validate(ddd), /internal-only/); checks++;
  const scaffold = mvcFixture(root);
  const decision = attachScaffoldDecisionFixture(path.join(root, 'decision-evidence'), { project_id: 'example', status: 'user-confirmed', confirmed_architecture: 'layered-mvc', decision_inputs_digest: `sha256:${'1'.repeat(64)}`, user_confirmation: { confirmation_ref: 'user-message', confirmed_by: 'user' } });
  const record = { status: 'current', template: false, decisions: [decision] };
  const recordFile = path.join(root, 'decision.json');
  writeFileSync(recordFile, JSON.stringify(record));
  scaffold.architecture = { ...scaffold.architecture, source_kind: 'scaffold-decision', decision_ref: 'decision.json', decision_digest: hash(readFileSync(recordFile)) }; scaffold.digest = technicalDigest(scaffold);
  assert.equal((await validate(scaffold)).architecture_family, 'layered-mvc'); checks++;
  record.decisions[0].status = 'awaiting-user-decision'; writeFileSync(recordFile, JSON.stringify(record)); scaffold.architecture.decision_digest = hash(readFileSync(recordFile)); scaffold.digest = technicalDigest(scaffold);
  await assert.rejects(() => validate(scaffold), /分支设计前必须确认/); checks++;
  record.decisions[0].status = 'user-confirmed'; record.decisions[0].user_confirmation.user_decision_ref = 'missing-user-decision.json'; writeFileSync(recordFile, JSON.stringify(record)); scaffold.architecture.decision_digest = hash(readFileSync(recordFile)); scaffold.digest = technicalDigest(scaffold);
  await assert.rejects(() => validate(scaffold), /user-decision/); checks++;
  const current = mvcFixture(root); current.status = 'approved'; current.digest = technicalDigest(current);
  const file = path.join(root, 'design.json'); writeFileSync(file, JSON.stringify(current));
  const technical_design = { ref: 'design.json', version: 'v1', digest: hash(readFileSync(file)) };
  const identity = { architecture_family: 'layered-mvc', architecture_profile: 'layered-mvc-service', generator_skill: 'yss-layered-mvc-scaffold-generator', requested_capabilities: [], resolved_modules: ['server','service','repository'], verification_database: 'h2', production_database: 'not-bound', contract_digest: 'a'.repeat(64) };
  const state = { technical_design, slice_id: 'slice.submit', architecture_identity: identity, conditions: ['backend-technical-design-impact'] };
  enforceTechnicalDesign(state, { root }); checks++;
  assert.throws(() => enforceTechnicalDesign({ ...state, technical_design: undefined }, { root }), /缺少已批准技术设计/); checks++;
  assert.throws(() => enforceTechnicalDesign({ ...state, architecture_identity: { architecture_family: 'domain-driven' } }, { root }), /架构不匹配/); checks++;
  const resolution = compileDefaultImplementationContract({ ...state, root, requiredCapabilities: ['contract.request-validation'], architecture_evidence: { engineering_baseline: identity, repository_registration: identity, manifest: identity } });
  assert.deepEqual(resolution.technical_design, technical_design); assert(!resolution.required_skills.includes('yss-domain')); checks++;
  writeFileSync(path.join(root, 'spec.md'), 'changed again');
  assert.equal(evaluateContractFreshness({ schema_version: 2, resolution }, { registry: loadSkillRegistry(), compilerContract: loadCompilerContract(), root }).freshness, 'stale'); checks++;
} finally { rmSync(root, { recursive: true, force: true }); }
process.stdout.write(`技术设计场景通过：${checks} 项（MVC、DDD、兼容、架构、承接、切片与漂移）\n`);
